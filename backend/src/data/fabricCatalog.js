/**
 * Returns list of fabric types for a given category name (case-insensitive)
 */
function getFabricTypesByCategory(categoryName) {
  if (!categoryName) return [];
  const trimmed = String(categoryName).trim().toLowerCase();
  const found = FABRIC_CATEGORIES.find(
    (c) => c.category.trim().toLowerCase() === trimmed
  );
  return found ? found.types : [];
}

/**
 * Validates if category exists in master catalog
 */
function isValidFabricCategory(categoryName) {
  if (!categoryName) return false;
  const trimmed = String(categoryName).trim().toLowerCase();
  return FABRIC_CATEGORIES.some(
    (c) => c.category.trim().toLowerCase() === trimmed
  );
}

/**
 * Validates if category and type combination is legitimate in master catalog
 */
function isValidFabricType(categoryName, typeName) {
  if (!categoryName || !typeName) return false;
  const types = getFabricTypesByCategory(categoryName);
  const trimmedType = String(typeName).trim().toLowerCase();
  return types.some((t) => t.trim().toLowerCase() === trimmedType);
}

module.exports = {
  FABRIC_CATEGORIES,
  getFabricTypesByCategory,
  isValidFabricCategory,
  isValidFabricType,
};
